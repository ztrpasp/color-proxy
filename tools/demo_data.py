def _expand_answer(model: str, question: str, answer: str) -> str:
    """Give demo answers enough substance for a visible token stream.

    The curated answer remains the first paragraph.  A short domain-specific second paragraph
    makes complete and streaming responses look closer to a real service without adding any
    external model dependency.
    """
    if normalize_question(question) == normalize_question("你是谁？"):
        return answer
    if model == "medical":
        extra = (
            " 从实际健康管理的角度，还可以同时观察症状出现的时间、变化趋势、是否影响进食睡眠或日常活动，"
            "以及是否伴随明显的危险信号。若情况持续不缓解、反复出现，或本人属于儿童、孕期、老年人及有基础疾病等特殊人群，"
            "建议结合既往病史和正在使用的药物，由医生进一步评估。以上信息用于一般健康知识参考，不能替代面对面的医学诊断。"
        )
    elif model == "education":
        extra = (
            " 实际办理时，建议先确认本人所属校区、学院、入学年级和当前学期，因为开放时间、材料要求与审批路径可能会随学期调整。"
            "如果线上系统显示的信息与学院通知不一致，可以保留申请记录或页面截图，并联系对应的教务、学生事务或信息化服务人员确认，"
            "这样更容易避免错过截止时间或重复提交。"
        )
    else:
        extra = ""
    return answer + extra


def answer_question(model: str, question: str) -> tuple[bool, str]:
    table = MEDICAL_QA if model == "medical" else EDUCATION_QA if model == "education" else {}
    answer = table.get(normalize_question(question))
    if answer is None:
        return False, "抱歉，当前服务暂时无法对这个问题给出可靠答案。你可以换一种更具体的问法，或选择与当前服务领域更相关的问题。"
    return True, _expand_answer(model, question, answer)


def monitor_point(location: str = "A", timestamp: float | None = None) -> dict:
    """Generate a deterministic-ish monitoring sample around realistic demo ranges."""
    ts = time.time() if timestamp is None else timestamp
    loc = location.upper() if location else "A"
    phase = ts / 7.0 + (0.0 if loc == "A" else 1.7)
    inbound = 612.0 + 92.0 * math.sin(phase) + 24.0 * math.sin(phase * 2.3)
    outbound = 438.0 + 68.0 * math.cos(phase * 0.91) + 18.0 * math.sin(phase * 1.7)
    latency = 14.8 + 2.7 * math.sin(phase * 1.21) + (1.2 if loc == "B" else 0.0)
    loss = max(0.0, 0.06 + 0.05 * math.sin(phase * 0.77))
    pps = int((inbound + outbound) * 104.0)
    connections = int(1850 + 260 * math.cos(phase * 0.63) + (180 if loc == "B" else 0))
    health = "healthy" if latency < 19 and loss < 0.15 else "attention"
    return {
        "timestamp": round(ts, 3),
        "location": loc,
        "inbound_mbps": round(inbound, 1),
        "outbound_mbps": round(outbound, 1),
        "pps": pps,
        "latency_ms": round(latency, 1),
        "loss_pct": round(loss, 2),
        "connections": connections,
        "health": health,
    }


def monitor_recent(location: str = "A", limit: int = 16) -> list[dict]:
    limit = max(1, min(limit, 60))
    now = time.time()
    return [monitor_point(location, now - (limit - 1 - i) * 2.0) for i in range(limit)]
