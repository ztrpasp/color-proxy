def _qa(items: list[tuple[str, str]]) -> dict[str, str]:
    return {normalize_question(q): a for q, a in items}


def normalize_question(text: str) -> str:
    text = text.strip().lower()
    text = re.sub(r"[？?！!。,.，；;：:\s]+$", "", text)
    text = re.sub(r"\s+", "", text)
    return text


